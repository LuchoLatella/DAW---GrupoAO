  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'rol_usuario_enum') THEN
    CREATE TYPE rol_usuario_enum AS ENUM ('ADMINISTRADOR', 'MEDICO', 'PACIENTE');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'estado_usuario_enum') THEN
    CREATE TYPE estado_usuario_enum AS ENUM ('ACTIVO', 'INACTIVO');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'reservas_estado_enum') THEN
    CREATE TYPE reservas_estado_enum AS ENUM ('RESERVADO', 'ATENDIDO', 'CANCELADO', 'AUSENTE');
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento VARCHAR(20) NOT NULL UNIQUE,
  nombres VARCHAR(100) NOT NULL,
  apellidos VARCHAR(100) NOT NULL,
  clave VARCHAR(255) NOT NULL,
  rol rol_usuario_enum NOT NULL,
  estado estado_usuario_enum NOT NULL DEFAULT 'ACTIVO'
);

CREATE TABLE IF NOT EXISTS medicos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INTEGER NOT NULL UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE,
  especialidad VARCHAR(100) NOT NULL,
  matricula VARCHAR(50),
  valor_consulta INTEGER NOT NULL CHECK (valor_consulta >= 0)
);

CREATE TABLE IF NOT EXISTS reservas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_medico INTEGER NOT NULL REFERENCES medicos(id) ON DELETE RESTRICT,
  id_paciente INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  fecha_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  monto_consulta INTEGER NOT NULL CHECK (monto_consulta >= 0),
  estado reservas_estado_enum NOT NULL DEFAULT 'RESERVADO'
);

-- No puede haber dos reservas activas para el mismo medico y horario.
CREATE UNIQUE INDEX IF NOT EXISTS ux_reservas_medico_fecha_reservado
  ON reservas (id_medico, fecha_hora)
  WHERE estado = 'RESERVADO';

CREATE INDEX IF NOT EXISTS ix_reservas_paciente ON reservas (id_paciente);
CREATE INDEX IF NOT EXISTS ix_reservas_medico_fecha ON reservas (id_medico, fecha_hora);

